// Historia 002 · clave de supervisor (grupo C3, criterios 44 a 53, 88, 91 y 113): la autorización de un solo
// uso que crea un supervisor con su PIN para una acción protegida de otra persona.
//
// - `autorizacion`: la sesión que la pidió, quién la pidió (`solicitante_id`), quién la dio (`autorizador_id`,
//   distinto del solicitante), la sucursal, el equipo de la sesión (si lo tiene), la acción (código de la
//   matriz de permisos), el motivo, cuándo vence (`expira_en`, 2 minutos después de crearla) y cuándo se usó
//   (`usada_en`). Se consume con un `UPDATE` condicional (misma sesión, acción y sucursal; sin usar y sin
//   vencer), así que dos peticiones concurrentes con la misma autorización no pueden usarla las dos.
//   Nunca guarda el PIN ni su huella.
// - Tabla de empresa trazable (`sqlTablaDeEmpresaTrazable`, con la llave hacia `equipo`), solo para
//   `restaurante_api` (SELECT, INSERT y UPDATE): la plataforma no la toca.
// - Agrega `sesion (id, empresa_id)` único, para que la autorización no pueda apuntar a una sesión de otra
//   empresa, y la llave de `auditoria.autorizacion_id` hacia `autorizacion`. La llave de la auditoría es
//   `NOT VALID`: la auditoría es inmutable, así que sus filas no se pueden corregir, y así revertir esta
//   migración (que borra las autorizaciones) y volver a aplicarla no choca con filas que ya las nombran.
// - Ajuste de C2: `equipo_recordado.orden` pasa de `GENERATED ALWAYS` a `GENERATED BY DEFAULT AS IDENTITY`. Con
//   `ALWAYS`, ningún `INSERT` puede copiar una fila completa (la prueba de inserción entre empresas de
//   `rls-acceso.spec.ts` lo hace con `jsonb_populate_record`) y la base lo rechaza con `428C9` antes de llegar
//   a la política RLS. El valor sigue saliendo de la secuencia cuando no se envía; no hay restricción de
//   unicidad que un valor enviado pudiera romper.
//
// `down` quita la llave de la auditoría, borra `autorizacion` con sus datos (el código de C3 ya no existiría),
// quita la unicidad de `sesion` y devuelve `orden` a `GENERATED ALWAYS`. Las filas de auditoría de la clave
// de supervisor se conservan.
import type { ContextoMigracion } from './tipos';
import { sqlTablaDeEmpresaTrazable } from './sql-tabla-de-empresa';

const SQL_UP = `
ALTER TABLE sesion ADD CONSTRAINT sesion_id_empresa_unico UNIQUE (id, empresa_id);

CREATE TABLE autorizacion (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  empresa_id uuid NOT NULL REFERENCES empresa (id),
  sesion_id uuid NOT NULL,
  solicitante_id uuid NOT NULL,
  autorizador_id uuid NOT NULL,
  sucursal_id uuid NOT NULL,
  equipo_id uuid,
  accion text NOT NULL CHECK (btrim(accion) <> ''),
  motivo text NOT NULL CHECK (char_length(motivo) BETWEEN 1 AND 300),
  expira_en timestamptz NOT NULL,
  usada_en timestamptz,
  creado_en timestamptz NOT NULL DEFAULT now(),
  actualizado_en timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT autorizacion_sesion_fk FOREIGN KEY (sesion_id, empresa_id) REFERENCES sesion (id, empresa_id),
  CONSTRAINT autorizacion_solicitante_fk
    FOREIGN KEY (solicitante_id, empresa_id) REFERENCES usuario (id, empresa_id),
  CONSTRAINT autorizacion_autorizador_fk
    FOREIGN KEY (autorizador_id, empresa_id) REFERENCES usuario (id, empresa_id),
  CONSTRAINT autorizacion_sucursal_fk
    FOREIGN KEY (sucursal_id, empresa_id) REFERENCES sucursal (id, empresa_id),
  CONSTRAINT autorizacion_equipo_fk FOREIGN KEY (equipo_id, empresa_id) REFERENCES equipo (id, empresa_id),
  -- Nadie se autoriza a sí mismo (criterio 45).
  CONSTRAINT autorizacion_distintos_ck CHECK (solicitante_id <> autorizador_id),
  CONSTRAINT autorizacion_id_empresa_unico UNIQUE (id, empresa_id)
);
CREATE INDEX autorizacion_empresa_id_idx ON autorizacion (empresa_id);
CREATE INDEX autorizacion_sesion_idx ON autorizacion (sesion_id);
${sqlTablaDeEmpresaTrazable('autorizacion', {
  privilegiosApi: ['SELECT', 'INSERT', 'UPDATE'],
  privilegiosPlataforma: [],
  llaveDeEquipo: true,
})}

ALTER TABLE auditoria
  ADD CONSTRAINT auditoria_autorizacion_fk
    FOREIGN KEY (autorizacion_id, empresa_id) REFERENCES autorizacion (id, empresa_id) NOT VALID;

ALTER TABLE equipo_recordado ALTER COLUMN orden SET GENERATED BY DEFAULT;
`;

const SQL_DOWN = `
ALTER TABLE equipo_recordado ALTER COLUMN orden SET GENERATED ALWAYS;
ALTER TABLE auditoria DROP CONSTRAINT auditoria_autorizacion_fk;
DROP TABLE autorizacion;
ALTER TABLE sesion DROP CONSTRAINT sesion_id_empresa_unico;
`;

export async function up({ sequelize, transaction }: ContextoMigracion): Promise<void> {
  await sequelize.query(SQL_UP, { transaction });
}

export async function down({ sequelize, transaction }: ContextoMigracion): Promise<void> {
  await sequelize.query(SQL_DOWN, { transaction });
}
